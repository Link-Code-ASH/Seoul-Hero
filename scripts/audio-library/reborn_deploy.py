"""Deploy the authorized reborn-01 selection; Music and preview renders are read-only.

This separate command intentionally never calls the preview renderer or legacy builder.
Old live WAVs remain available for comparisons and rollback, outside the new bundle glob.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import wave

ROOT = Path(__file__).resolve().parents[2]
PREVIEW = ROOT / 'audio-library/reborn-01'
DEPLOYED = ROOT / 'assets/audio/sfx/reborn-01'


def digest(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()


def write_json(file, value):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def verify_candidates(manifest):
    problems = json.loads((PREVIEW / 'verification.json').read_text(encoding='utf-8'))['problems']
    if problems:
        raise ValueError('Preview contains unresolved validation errors')
    files = []
    for cue_id, cue in manifest['cues'].items():
        for variant in cue['variants']:
            source = (PREVIEW / variant['file']).resolve()
            if not source.is_relative_to((PREVIEW / 'sounds').resolve()):
                raise ValueError(f'Unexpected sound path: {source}')
            if digest(source) != variant['sha256']:
                raise ValueError(f'Candidate hash changed: {source}')
            with wave.open(str(source)) as wav:
                expected_channels = 2 if variant['loop'] else 1
                if (wav.getframerate(), wav.getsampwidth(), wav.getnchannels()) != (48000, 2, expected_channels):
                    raise ValueError(f'Unexpected sound format: {source}')
            files.append((cue_id, variant, source))
    if len(files) != 128 or len(manifest['cues']) != 44:
        raise ValueError('Incomplete reborn-01 selection')
    return files


def deploy():
    manifest = json.loads((PREVIEW / 'manifest.json').read_text(encoding='utf-8'))
    candidates = verify_candidates(manifest)
    # Keep the old mapped files independently of future asset pruning.
    old_content = PREVIEW / 'rollback/files/godot/data/content.json'
    if not old_content.exists():
        old_content.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / 'godot/data/content.json', old_content)
    content = json.loads(old_content.read_text(encoding='utf-8'))
    old_files = []
    for cue in content['sfx'].values():
        for url in cue['urls']:
            relative = url.removeprefix('res://')
            source = ROOT / 'godot' / relative
            target = PREVIEW / 'rollback/files' / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists():
                shutil.copy2(source, target)
            old_files.append({'file': relative, 'sha256': digest(target)})
    settings, paths, provenance = {}, {}, {}
    for cue_id, cue in manifest['cues'].items():
        settings[cue_id] = {key: cue[key] for key in (
            'label', 'gain', 'interval', 'concurrency', 'priority', 'pitch', 'volumeVariation', 'protected')}
        settings[cue_id]['group'] = cue['category']
        settings[cue_id]['loop'] = cue.get('loop', False)
        paths[cue_id] = []
        provenance[cue_id] = {'label': cue['label'], 'note': cue['note'], 'variants': []}
    for cue_id, variant, source in candidates:
        relative = Path(cue_id) / source.name
        target = DEPLOYED / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        paths[cue_id].append('sfx/reborn-01/' + relative.as_posix())
        provenance[cue_id]['variants'].append({**variant, 'file': relative.as_posix()})
    policy = {**manifest['policy'], 'status': 'deployed; user authorized full adoption without listening approval'}
    connections = {**manifest['connections'], 'status': 'deployed'}
    def literal(value):
        return json.dumps(value, ensure_ascii=False, indent=2)
    generated = '// Generated by scripts/audio-library/reborn_deploy.py from the authorized reborn-01 manifest.\n'
    generated += '// Old sounds and original trims remain in audio-library/reborn-01/rollback and manifest.json.\n'
    for name, value in [('sourcedSfxPaths', paths), ('sourcedSfxSettings', settings),
                        ('sourcedAudioPolicy', policy), ('sourcedAudioConnections', connections)]:
        generated += f'export const {name} = {literal(value)} as const;\n\n'
    (ROOT / 'src/data/sourcedAudio.ts').write_text(generated, encoding='utf-8')
    write_json(DEPLOYED / 'provenance.json', {
        'revision': 'reborn-01', 'source': 'Sonniss GDC 2026 bundle 1–5, user-provided Music archive',
        'source_unchanged': True, 'manifest': 'audio-library/reborn-01/manifest.json',
        'licenses': 'audio-library/reborn-01/provenance/', 'policy': policy,
        'connections': connections, 'cues': provenance,
    })
    write_json(PREVIEW / 'rollback/audio-files.json', old_files)
    write_json(PREVIEW / 'deployment.json', {
        'revision': 'reborn-01', 'authorization': 'User authorized all sounds and mix policies; no listening approval required',
        'cues': 44, 'one_shot_cues': 39, 'ambience_cues': 5, 'files': len(candidates),
        'bytes': sum(source.stat().st_size for _, _, source in candidates),
        'assets': [{'file': str(target.relative_to(ROOT)).replace('\\', '/'), 'sha256': digest(target)}
                   for target in sorted(DEPLOYED.rglob('*.wav'))],
        'bgm': {str(file.relative_to(ROOT)).replace('\\', '/'): digest(file)
                for file in sorted((ROOT / 'assets/audio/bgm/provided').glob('*.mp3'))},
        'runtime_verification': 'pending', 'direct_listening': 'not performed; signal analysis and editing only',
        'rollback': 'rollback/files plus preserved old live assets; see README.md',
    })
    print(json.dumps({'deployed_cues': len(paths), 'files': len(candidates), 'old_files_preserved': len(old_files)}))


def verify_deployment():
    report = json.loads((PREVIEW / 'deployment.json').read_text(encoding='utf-8'))
    content = json.loads((ROOT / 'godot/data/content.json').read_text(encoding='utf-8'))
    old = json.loads((PREVIEW / 'rollback/files/godot/data/content.json').read_text(encoding='utf-8'))
    problems = []
    for asset in report['assets']:
        source = ROOT / asset['file']
        target = ROOT / 'godot' / asset['file']
        for file in (source, target):
            if not file.exists() or digest(file) != asset['sha256']:
                problems.append(f'Asset mismatch: {file.relative_to(ROOT)}')
    for relative, expected in report['bgm'].items():
        for file in (ROOT / relative, ROOT / 'godot' / relative):
            if not file.exists() or digest(file) != expected:
                problems.append(f'BGM changed: {file.relative_to(ROOT)}')
    for id, cue in content['sfx'].items():
        if not cue['urls'] or any('/sfx/reborn-01/' not in url for url in cue['urls']):
            problems.append(f'Incomplete cue: {id}')
    mappings = content['audioConnections']
    required = list(mappings['enemyActions'].values()) + list(mappings['lobbyBackgrounds'].values())
    required += [id for stages in mappings['weaponStages'].values() for id in stages.values() if isinstance(id, str)]
    problems += [f'Missing mapping: {id}' for id in required if id not in content['sfx']]
    # Only presentation data may differ; exported combat/economy/save data must match.
    allowed = {'sfx', 'audioConfig', 'audioConnections'}
    problems += [f'Unexpected content change: {key}' for key, value in old.items()
                 if key not in allowed and content.get(key) != value]
    if len(content['sfx']) != 44 or content['bgm']['combat']['gain'] != .12:
        problems.append('Cue count/combat BGM gain mismatch')
    write_json(PREVIEW / 'qa/deployed-data.json', {
        'scope': 'deployed source/Godot WAV hashes, BGM hashes, mapping coverage, unchanged combat/save/content',
        'files': len(report['assets']), 'cues': len(content['sfx']), 'bgm': len(report['bgm']),
        'problems': problems, 'gameplay_listening_full_build': 'not performed',
    })
    print(json.dumps({'checked_files': len(report['assets']), 'cues': len(content['sfx']), 'problems': problems}))
    if problems:
        raise SystemExit(1)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--deploy', action='store_true')
    action.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    deploy() if args.deploy else verify_deployment()
